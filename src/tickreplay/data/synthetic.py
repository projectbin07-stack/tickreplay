"""Seeded SYNTHETIC price generators.

Nothing here is market data. Both generators draw from :class:`random.Random` seeded by
the caller, so the same arguments give the same bars. They exist so the engine can be
exercised and tested without shipping or depending on real prices; a strategy that does
well on these series has demonstrated nothing about real markets.

* :func:`gbm_bars` - geometric Brownian motion (a random walk in log price with drift).
* :func:`ou_bars` - an Ornstein-Uhlenbeck (mean-reverting) process in log price.

Each bar is built from ``substeps`` simulated points: the open is the previous close,
high/low are the extremes of the path, and the close is the last point. Bars are
contiguous in time (no weekends or sessions), like a 24/7 market.
"""

from __future__ import annotations

import math
import random
from collections.abc import Callable
from datetime import datetime, timedelta, timezone
from decimal import ROUND_HALF_EVEN, Decimal

from tickreplay.events import Bar

SYNTHETIC_NOTICE = "SYNTHETIC DATA - generated by tickreplay, not real market prices"
SECONDS_PER_YEAR = 365.25 * 24 * 3600
DEFAULT_START = datetime(2024, 1, 1, tzinfo=timezone.utc)
_CENT = Decimal("0.01")


def _to_price(value: float) -> Decimal:
    return max(Decimal(repr(value)).quantize(_CENT, rounding=ROUND_HALF_EVEN), _CENT)


def _check(n: int, interval: timedelta, sigma: float, substeps: int, base_volume: int) -> None:
    if n <= 0:
        raise ValueError("n must be positive")
    if interval <= timedelta(0):
        raise ValueError("interval must be positive")
    if sigma < 0:
        raise ValueError("sigma must be non-negative")
    if substeps < 1:
        raise ValueError("substeps must be at least 1")
    if base_volume < 0:
        raise ValueError("base_volume must be non-negative")


def _build(
    step: Callable[[float], float],
    rng: random.Random,
    *,
    n: int,
    start_log: float,
    symbol: str,
    start: datetime,
    interval: timedelta,
    substeps: int,
    base_volume: int,
) -> list[Bar]:
    bars: list[Bar] = []
    x = start_log
    close = _to_price(math.exp(x))
    for i in range(n):
        open_ = close
        high = low = open_
        for _ in range(substeps):
            x = step(x)
            close = _to_price(math.exp(x))
            high = max(high, close)
            low = min(low, close)
        volume = Decimal(round(base_volume * math.exp(0.5 * rng.gauss(0.0, 1.0))))
        bars.append(Bar(start + i * interval, symbol, open_, high, low, close, volume))
    return bars


def gbm_bars(
    *,
    seed: int,
    n: int,
    symbol: str = "SYN-GBM",
    start: datetime = DEFAULT_START,
    interval: timedelta = timedelta(hours=1),
    start_price: float = 100.0,
    mu: float = 0.05,
    sigma: float = 0.6,
    substeps: int = 4,
    base_volume: int = 50_000,
) -> list[Bar]:
    """Synthetic bars from geometric Brownian motion.

    ``mu`` and ``sigma`` are annualised drift and volatility of the price.
    """
    _check(n, interval, sigma, substeps, base_volume)
    if start_price <= 0:
        raise ValueError("start_price must be positive")
    rng = random.Random(seed)
    dt = interval.total_seconds() / SECONDS_PER_YEAR / substeps
    drift = (mu - 0.5 * sigma * sigma) * dt
    diffusion = sigma * math.sqrt(dt)

    def step(x: float) -> float:
        return x + drift + diffusion * rng.gauss(0.0, 1.0)

    return _build(
        step,
        rng,
        n=n,
        start_log=math.log(start_price),
        symbol=symbol,
        start=start,
        interval=interval,
        substeps=substeps,
        base_volume=base_volume,
    )


def ou_bars(
    *,
    seed: int,
    n: int,
    symbol: str = "SYN-OU",
    start: datetime = DEFAULT_START,
    interval: timedelta = timedelta(hours=1),
    start_price: float = 100.0,
    mean_price: float = 100.0,
    theta: float = 200.0,
    sigma: float = 0.6,
    substeps: int = 4,
    base_volume: int = 50_000,
) -> list[Bar]:
    """Synthetic bars from a mean-reverting (Ornstein-Uhlenbeck) process in log price.

    ``theta`` is the annualised speed of reversion toward ``mean_price``; ``sigma`` is
    the annualised volatility of the log price.
    """
    _check(n, interval, sigma, substeps, base_volume)
    if start_price <= 0 or mean_price <= 0:
        raise ValueError("prices must be positive")
    if theta < 0:
        raise ValueError("theta must be non-negative")
    rng = random.Random(seed)
    dt = interval.total_seconds() / SECONDS_PER_YEAR / substeps
    target = math.log(mean_price)
    diffusion = sigma * math.sqrt(dt)

    def step(x: float) -> float:
        return x + theta * (target - x) * dt + diffusion * rng.gauss(0.0, 1.0)

    return _build(
        step,
        rng,
        n=n,
        start_log=math.log(start_price),
        symbol=symbol,
        start=start,
        interval=interval,
        substeps=substeps,
        base_volume=base_volume,
    )
